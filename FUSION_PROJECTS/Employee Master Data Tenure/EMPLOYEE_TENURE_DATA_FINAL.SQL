SELECT
  PAPF.PERSON_NUMBER         EMPLOYEE_ID, 
  PPNF.DISPLAY_NAME          FULL_NAME,
  HAOU.NAME                  DEPARTMENT, 
  PJFT.NAME                  JOB_TITLE,
  MGR_NAME.DISPLAY_NAME      MANAGER_NAME,
  TO_CHAR(PPOS.DATE_START,'YYYY-MM-DD')	 HIRE_DATE ,
  TO_CHAR(NVL(PPOS.ACTUAL_TERMINATION_DATE,SYSDATE-1),'YYYY-MM-DD')  LAST_WORKING_DATE,
	CASE
		WHEN PPOS.ACTUAL_TERMINATION_DATE != SYSDATE THEN
    TRUNC(MONTHS_BETWEEN(PPOS.ACTUAL_TERMINATION_DATE, PPOS.DATE_START) / 12) || ' Years / ' ||
    TRUNC(MOD (MONTHS_BETWEEN(PPOS.ACTUAL_TERMINATION_DATE, PPOS.DATE_START), 12)) || ' Months / ' ||
    TRUNC(PPOS.ACTUAL_TERMINATION_DATE - (ADD_MONTHS(PPOS.DATE_START, TRUNC(MONTHS_BETWEEN(PPOS.ACTUAL_TERMINATION_DATE, PPOS.DATE_START))))) || ' Days'
		ELSE TO_CHAR(SYSDATE -1)
   END TENURE ,
	CASE
	WHEN PSDF.SENIORITY_LOS_YEARS IS NOT NULL THEN 
	 NVL(PSDF.SENIORITY_LOS_YEARS, NULL) || ' Year, ' ||
	 NVL(PSDF.SENIORITY_LOS_MONTHS, NULL) || ' Months, ' ||
	 NVL(PSDF.SENIORITY_LOS_DAYS, NULL) || ' Days' 
	 ELSE NULL
	END SENIORITY_DATE
FROM PER_ALL_PEOPLE_F                   PAPF   
INNER JOIN PER_PERSON_NAMES_F           PPNF        ON PPNF.PERSON_ID = PAPF.PERSON_ID
                                                   AND SYSDATE BETWEEN PPNF.EFFECTIVE_START_DATE AND PPNF.EFFECTIVE_END_DATE
                                                   AND PPNF.NAME_TYPE = 'GLOBAL'
INNER JOIN PER_ALL_ASSIGNMENTS_M        PAAM        ON PAAM.PERSON_ID = PAPF.PERSON_ID
                                                   AND SYSDATE BETWEEN PAAM.EFFECTIVE_START_DATE AND PAAM.EFFECTIVE_END_DATE
                                                   AND PAAM.PRIMARY_FLAG = 'Y'
INNER JOIN HR_ALL_ORGANIZATION_UNITS    HAOU        ON HAOU.ORGANIZATION_ID = PAAM.ORGANIZATION_ID
INNER JOIN PER_JOBS_F_TL                PJFT        ON PJFT.JOB_ID = PAAM.JOB_ID
                                                   AND SYSDATE BETWEEN PJFT.EFFECTIVE_START_DATE AND PJFT.EFFECTIVE_END_DATE
                                                   AND PJFT.LANGUAGE = 'US'
INNER JOIN PER_ASSIGNMENT_SUPERVISORS_F PASF        ON PASF.ASSIGNMENT_ID =PAAM.ASSIGNMENT_ID
                                                   AND PASF.MANAGER_TYPE = 'LINE_MANAGER'
INNER JOIN PER_ALL_PEOPLE_F             MGR_PAPF    ON MGR_PAPF.PERSON_ID = PASF.MANAGER_ID
INNER JOIN PER_PERSON_NAMES_F           MGR_NAME    ON MGR_NAME.PERSON_ID = PASF.MANAGER_ID
                                                   AND SYSDATE BETWEEN MGR_NAME.EFFECTIVE_START_DATE AND MGR_NAME.EFFECTIVE_END_DATE
                                                   AND MGR_NAME.NAME_TYPE = 'GLOBAL'
INNER JOIN PER_PERIODS_OF_SERVICE       PPOS        ON PPOS.PERSON_ID = PAPF.PERSON_ID AND PPOS.PRIMARY_FLAG = 'Y'
LEFT OUTER JOIN PER_SENIORITY_DATES_F   PSDF        ON PSDF.PERSON_ID = PAPF.PERSON_ID
                                                   AND SYSDATE BETWEEN PSDF.EFFECTIVE_START_DATE AND PSDF.EFFECTIVE_END_DATE
WHERE 1=1
AND SYSDATE BETWEEN PAPF.EFFECTIVE_START_DATE AND PAPF.EFFECTIVE_END_DATE
AND PAPF.PERSON_NUMBER = NVL(:P_EMPLOYEE_ID ,PAPF.PERSON_NUMBER )
AND PPNF.DISPLAY_NAME = NVL(:P_FULL_NAME ,PPNF.DISPLAY_NAME)

