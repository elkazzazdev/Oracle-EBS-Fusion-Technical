------ PIVOT TABLE TO GET ALL SALARY ---- 
-- =============================================================
SELECT 
    XMO.ORG_NAME,
    SUM(CASE WHEN XME.DEPARTMENT_ID = XMD.DEPARTMENT_ID  THEN XME.SALARY ELSE 0 END) HR_SALARY,
    SUM(CASE WHEN XME.DEPARTMENT_ID = XMD.DEPARTMENT_ID  THEN XME.SALARY ELSE 0 END) FIN_SALARY,
    SUM(CASE WHEN XME.DEPARTMENT_ID = XMD.DEPARTMENT_ID  THEN XME.SALARY ELSE 0 END) SALES_SALARY,
    SUM(CASE WHEN XME.DEPARTMENT_ID = XMD.DEPARTMENT_ID  THEN XME.SALARY ELSE 0 END) IT_SALARY,
    SUM(XME.SALARY) TOTAL_ORG_SALARY ,
    COUNT(XME.EMPLOYEE_ID) EMP_COUNT,
    COUNT(XMD.DEPARTMENT_ID) DEPT_COUNT,
NULL
FROM XX_MK_ORGANIZATIONS             XMO
INNER JOIN XX_MK_DEPARTMENTS         XMD ON XMD.ORG_ID = XMO.ORG_ID
INNER JOIN XX_MK_JOBS                XMJ ON XMJ.JOB_ID = XMD.JOB_ID
LEFT OUTER JOIN XX_MK_EMPLOYEES      XME ON XME.DEPARTMENT_ID = XMD.DEPARTMENT_ID
WHERE 1=1 
GROUP BY XMO.ORG_NAME;
--- OUTPUT > TOTAL_ORG_SALARY
