CREATE TABLE  XX_MK_ORGANIZATIONS  (
    ORG_ID              NUMBER ,
    LEGAL_NUMBER        NUMBER ,
    ORG_NAME            VARCHAR2 (100) NOT NULL,
    COUNTRY             VARCHAR2 (100),
    START_DATE          DATE DEFAULT SYSDATE NOT NULL ,
    END_DATE            DATE ,
    -- 5 WHO 
    CREATED_BY          NUMBER NOT NULL,
    CREATION_DATE       DATE DEFAULT SYSDATE NOT NULL, -- UPDATE THIS TYPE TO SYSTIMESTAMP 
    LAST_UPDATED_BY     NUMBER NOT NULL,
    LAST_UPDATE_DATE    DATE DEFAULT SYSDATE NOT NULL, -- AND THIS TO UPDATEED
    LAST_UPDATE_LOGIN   NUMBER,

    CONSTRAINT ORG_ID_PK    PRIMARY KEY (ORG_ID),
    CONSTRAINT ORG_NAME_UK  UNIQUE (ORG_NAME) -- UNIQUE NAME 
);

CREATE TABLE  XX_MK_DEPARTMENTS  (
    DEPARTMENT_ID       NUMBER ,
    DEPARTMENT_NAME     VARCHAR2(100) NOT NULL,
    START_DATE          DATE DEFAULT SYSDATE,
    ORG_ID              NUMBER,

    CONSTRAINT DEPT_ID_PK   PRIMARY KEY (DEPARTMENT_ID),
    CONSTRAINT DEPT_ORG_FK  FOREIGN KEY (ORG_ID) REFERENCES  XX_MK_ORGANIZATIONS (ORG_ID) 
);

CREATE TABLE  XX_MK_JOBS  (
    JOB_ID      NUMBER ,
    JOB_NAME    VARCHAR2(100) NOT NULL,
    MIN_SALARY  NUMBER (10,2) , -- THIS COLUMN FOR MIN SALARY ON THIS JOB 
    START_DATE  DATE DEFAULT SYSDATE NOT NULL, 
    DEPARTMENT_ID NUMBER , -- ACCEPT NULL 
    ORG_ID NUMBER ,
    CONSTRAINT JOB_ID_PK            PRIMARY KEY (JOB_ID),
    CONSTRAINT JOB_ORG_FK           FOREIGN KEY (ORG_ID) REFERENCES  XX_MK_ORGANIZATIONS (ORG_ID),
    CONSTRAINT JOB_DEPT_FK          FOREIGN KEY (DEPARTMENT_ID) REFERENCES  XX_MK_DEPARTMENTS (DEPARTMENT_ID),
    CONSTRAINT JOB_NAME_UK          UNIQUE (JOB_NAME) , -- UNIQUE NAME FOR JOB TO NO DUPLICATE 
    CONSTRAINT JOB_MIN_SALARY_CK    CHECK (MIN_SALARY >= 0) -- THE SALARY TO ENSURE SALARY > 0 
);

CREATE TABLE  XX_MK_EMPLOYEES  (
    EMPLOYEE_ID         NUMBER ,
    FIRST_NAME          VARCHAR2 (100) NOT NULL,
    LAST_NAME           VARCHAR2 (100) NOT NULL , 
    EMAIL               VARCHAR2 (100) ,   -- UNIQUE
    WORK_PHONE_NUMBER   VARCHAR2 (50), -- I CHOSE VARCHAR2 TO SHOW PHONE NUMBER FULL WITH 0 
    MANAGER_ID          NUMBER ,    -- SELF FK 
    SALARY              NUMBER(10,2) DEFAULT 0 , 
    ORG_ID              NUMBER ,    -- ACCEPT NULL
    DEPARTMENT_ID       NUMBER ,    -- ACCEPT NULL
    JOB_ID              NUMBER ,    -- ACCEPT NULL
    HIRE_DATE           DATE DEFAULT SYSDATE NOT NULL ,
    CONSTRAINT XX_EMP_ID_PK            PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT XX_EMP_EMAIL_UK         UNIQUE (EMAIL),
    CONSTRAINT XX_EMP_SALARY_CK        CHECK (SALARY >= 0 ),
    CONSTRAINT XX_EMP_MANAGER_ID_FK    FOREIGN KEY (MANAGER_ID)        REFERENCES  XX_MK_EMPLOYEES  (EMPLOYEE_ID) ,
    CONSTRAINT XX_EMP_JOB_ID_FK        FOREIGN KEY (JOB_ID)            REFERENCES  XX_MK_JOBS  (JOB_ID),
    CONSTRAINT XX_EMP_ORG_ID_FK        FOREIGN KEY (ORG_ID)            REFERENCES  XX_MK_ORGANIZATIONS (ORG_ID) ,
    CONSTRAINT XX_EMP_DEPT_ID_FK       FOREIGN KEY (DEPARTMENT_ID)     REFERENCES  XX_MK_DEPARTMENTS (DEPARTMENT_ID) 
);

