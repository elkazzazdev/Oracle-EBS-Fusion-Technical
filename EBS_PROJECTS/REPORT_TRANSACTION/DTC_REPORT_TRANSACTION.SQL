SELECT 
    RCTA.CT_REFERENCE                       REFERENCE ,
    RCTA.TRX_NUMBER                         INVOICE_NUMBER ,
    TO_CHAR (RCTA.TRX_DATE, 'DD-MON-YYYY')  INVOICE_DATE,
    RCTA.INVOICE_CURRENCY_CODE              CURRENCY,
    RCTA.ORG_ID                             ORGANIZATION_NUMBER,
    HP.PARTY_NUMBER                         CUSTOMER_NUMBER ,
    HP.PARTY_NAME                           CUSTOMER_NAME,
    HP.CATEGORY_CODE ,
    RBSA.NAME                               SOURCE_NAME ,
    RCTLA.EXTENDED_AMOUNT                   INV_AMOUNT ,
    RCTLA.LINE_NUMBER ,
    RCTLA.DESCRIPTION                       ITEM_DESCRIPTION, 
    MSIB.SEGMENT1                           ITEM_NAME,
    NVL(RCTLA.UNIT_SELLING_PRICE,0)         UNIT_PRICE,
    NVL(RCTLA.QUANTITY_INVOICED,0)          QUANTITY,  
    RCTLA.EXTENDED_AMOUNT                   AMOUNT,
    RCTTA.NAME                              TYPE_NAME,
    RCTA.SHIP_VIA,
    RCTA.TERM_DUE_DATE                      DUE_DATE,
    GL.SHORT_NAME                           LEGAL_ENTITY,
    HP.TOTAL_ORDERED_AMOUNT , 
    HP.TOTAL_NUM_OF_ORDERS , 
    HP_SOLD.PARTY_NAME                      SOLD_TO_CUSTOMER_NAME,
    HCA_SOLD.ACCOUNT_NUMBER                 SOLD_TO_CUSTOMER_NUMBER,
    HP_SHIP.PARTY_NAME                      SHIP_TO_CUSTOMER_NAME,
    HCA_SHIP.ACCOUNT_NUMBER                 SHIP_TO_CUSTOMER_NUMBER,
    HCSUA_SHIP.LOCATION                     SHIP_TO_LOCATION,
    HL_SHIP.ADDRESS1                        SHIP_TO_ADDRESS1,
    HL_SHIP.CITY                            SHIP_TO_CITY,
    HL_SHIP.STATE                           SHIP_TO_STATE,
    HL_SHIP.POSTAL_CODE                     SHIP_TO_POSTAL_CODE,
    HL_SHIP.COUNTRY                         SHIP_TO_COUNTRY,
    HP_SHIP_C.PARTY_NAME                    SHIP_TO_CONTACT_NAME,
    HP_BILL.PARTY_NAME                      BILL_TO_CUSTOMER_NAME,
    HCA_BILL.ACCOUNT_NUMBER                 BILL_TO_CUSTOMER_NUMBER,
    HCSUA_BILL.LOCATION                     BILL_TO_LOCATION,
    HL_BILL.ADDRESS1                        BILL_TO_ADDRESS1,
    HL_BILL.CITY                            BILL_TO_CITY,
    HL_BILL.STATE                           BILL_TO_STATE,
    HL_BILL.POSTAL_CODE                     BILL_TO_POSTAL_CODE,
    HL_BILL.COUNTRY                         BILL_TO_COUNTRY,
    HP_BILL_C.PARTY_NAME                    BILL_TO_CONTACT_NAME,
    RT.NAME                                 PAYMENT_TERM,
    RT.DESCRIPTION                          TERM_DESCRIPTION,
    ARM.NAME                                RECEIPT_METHOD_NAME,
    ARM.PAYMENT_CHANNEL_CODE ,
    ITE.BANK_BRANCH_NAME                    CUSTOMER_BANK_BRANCH,
    ITE.BANK_NAME                           CUSTOMER_BANK_NAME,
    ITE.BANK_NUMBER                         CUSTOMER_BANK_NUMBER,
    ITE.ACCOUNT_NUMBER                      CUSTOMER_INSTRUMENT_NUMBER,
    ITE.INSTRUMENT_TYPE,
    ITE.PAYMENT_CHANNEL_NAME,
    ITE.TRXN_REF_NUMBER1,
    IEBA.IBAN ,
    IEBA.EXT_BANK_ACCOUNT_ID,
    IEBA.BANK_ACCOUNT_NUM ,
    CASE WHEN RCTTA.TYPE = 'CM' THEN 'Credit Memo'
         WHEN RCTTA.TYPE = 'INV' THEN 'Invoice'
         ELSE RCTTA.TYPE 
    END CLASS_TYPE,
   (SELECT SUM(XXRCTLA.QUANTITY_INVOICED ) 
        FROM RA_CUSTOMER_TRX_LINES_ALL XXRCTLA 
        WHERE XXRCTLA.LINE_TYPE ='LINE' 
        AND XXRCTLA.CUSTOMER_TRX_ID = RCTLA.CUSTOMER_TRX_ID ) TOTAL_QUANTITY,  
    (SELECT NVL(SUM(XXRCTLA.EXTENDED_AMOUNT),0) 
        FROM RA_CUSTOMER_TRX_LINES_ALL XXRCTLA 
        WHERE XXRCTLA.LINE_TYPE ='LINE' 
        AND XXRCTLA.CUSTOMER_TRX_ID = RCTLA.CUSTOMER_TRX_ID ) TOTAL_INV,
    (SELECT  NVL(SUM(TXRCTLA.EXTENDED_AMOUNT),0)
        FROM RA_CUSTOMER_TRX_LINES_ALL TXRCTLA 
        WHERE TXRCTLA.LINE_TYPE ='TAX' 
        AND TXRCTLA.CUSTOMER_TRX_ID = RCTLA.CUSTOMER_TRX_ID ) TOTAL_TAX,
    (SELECT SUM(GT_RCTLA.EXTENDED_AMOUNT) 
        FROM RA_CUSTOMER_TRX_LINES_ALL GT_RCTLA 
        WHERE GT_RCTLA.LINE_TYPE IN ('LINE', 'TAX') 
        AND GT_RCTLA.CUSTOMER_TRX_ID = RCTLA.CUSTOMER_TRX_ID) GRAND_TOTAL 

FROM RA_CUSTOMER_TRX_ALL                    RCTA
INNER JOIN RA_CUST_TRX_TYPES_ALL            RCTTA               ON RCTTA.CUST_TRX_TYPE_ID = RCTA.CUST_TRX_TYPE_ID
                                                                AND RCTTA.ORG_ID = RCTA.ORG_ID
                                                                AND RCTTA.LEGAL_ENTITY_ID = RCTA.LEGAL_ENTITY_ID 
                                                                AND RCTTA.SET_OF_BOOKS_ID = RCTA.SET_OF_BOOKS_ID
INNER JOIN RA_CUSTOMER_TRX_LINES_ALL        RCTLA               ON RCTLA.CUSTOMER_TRX_ID = RCTA.CUSTOMER_TRX_ID
                                                                AND RCTLA.LINE_TYPE = 'LINE'
                                                                AND RCTLA.ORG_ID = RCTA.ORG_ID
INNER JOIN RA_BATCH_SOURCES_ALL             RBSA                ON RBSA.BATCH_SOURCE_ID = RCTA.BATCH_SOURCE_ID
                                                                AND RBSA.ORG_ID=RCTA.ORG_ID
INNER JOIN HZ_CUST_ACCOUNTS                 HCA                 ON HCA.CUST_ACCOUNT_ID = RCTA.BILL_TO_CUSTOMER_ID 
INNER JOIN HZ_PARTIES                       HP                  ON HP.PARTY_ID = HCA.PARTY_ID 
INNER JOIN GL_LEDGERS                       GL                  ON GL.LEDGER_ID = RCTA.SET_OF_BOOKS_ID
                                                                AND GL.COMPLETE_FLAG = 'Y'
INNER JOIN HZ_CUST_ACCOUNTS                 HCA_SOLD            ON HCA_SOLD.CUST_ACCOUNT_ID = RCTA.SOLD_TO_CUSTOMER_ID 
INNER JOIN HZ_PARTIES                       HP_SOLD             ON HP_SOLD.PARTY_ID = HCA_SOLD.PARTY_ID 

LEFT OUTER JOIN AR_SYSTEM_PARAMETERS_ALL    ARSP                ON ARSP.ORG_ID = RCTA.ORG_ID
                                                                AND ARSP.SET_OF_BOOKS_ID = RCTA.SET_OF_BOOKS_ID
LEFT OUTER JOIN MTL_SYSTEM_ITEMS_B          MSIB                ON MSIB.INVENTORY_ITEM_ID = RCTLA.INVENTORY_ITEM_ID
                                                                AND MSIB.ORGANIZATION_ID = ARSP.ORG_ID
                                                                AND MSIB.ORGANIZATION_ID = RCTLA.ORG_ID
                                                                AND MSIB.ENABLED_FLAG = 'Y'
LEFT OUTER JOIN IBY_TRXN_EXTENSIONS_V        ITE                ON ITE.TRXN_EXTENSION_ID = RCTA.PAYMENT_TRXN_EXTENSION_ID
LEFT OUTER JOIN IBY_EXT_BANK_ACCOUNTS        IEBA               ON IEBA.EXT_BANK_ACCOUNT_ID = ITE.INSTRUMENT_ID 
LEFT OUTER JOIN RA_TERMS                     RT                 ON RT.TERM_ID = RCTA.TERM_ID 
LEFT OUTER JOIN AR_RECEIPT_METHODS           ARM                ON ARM.RECEIPT_METHOD_ID = RCTA.RECEIPT_METHOD_ID 
LEFT OUTER JOIN HZ_CUST_ACCOUNTS             HCA_SHIP           ON HCA_SHIP.CUST_ACCOUNT_ID = RCTA.SHIP_TO_CUSTOMER_ID 
LEFT OUTER JOIN HZ_PARTIES                   HP_SHIP            ON HP_SHIP.PARTY_ID = HCA_SHIP.PARTY_ID 
LEFT OUTER JOIN HZ_CUST_SITE_USES_ALL        HCSUA_SHIP         ON HCSUA_SHIP.SITE_USE_ID   = RCTA.SHIP_TO_SITE_USE_ID 
LEFT OUTER JOIN HZ_CUST_ACCT_SITES_ALL       HCAA_SHIP          ON HCAA_SHIP.CUST_ACCT_SITE_ID = HCSUA_SHIP.CUST_ACCT_SITE_ID 
LEFT OUTER JOIN HZ_PARTY_SITES               HPS_SHIP           ON HPS_SHIP.PARTY_SITE_ID  = HCAA_SHIP.PARTY_SITE_ID 
LEFT OUTER JOIN HZ_LOCATIONS                 HL_SHIP            ON HL_SHIP.LOCATION_ID  = HPS_SHIP.LOCATION_ID 
LEFT OUTER JOIN HZ_CUST_ACCOUNT_ROLES        HCAR_SHIP_C        ON HCAR_SHIP_C.CUST_ACCOUNT_ROLE_ID = RCTA.SHIP_TO_CONTACT_ID 
LEFT OUTER JOIN HZ_PARTIES                   HP_SHIP_C          ON HP_SHIP_C.PARTY_ID = HCAR_SHIP_C.PARTY_ID 
LEFT OUTER JOIN HZ_CUST_ACCOUNTS             HCA_BILL           ON HCA_BILL.CUST_ACCOUNT_ID = RCTA.BILL_TO_CUSTOMER_ID 
LEFT OUTER JOIN HZ_PARTIES                   HP_BILL            ON HP_BILL.PARTY_ID = HCA_BILL.PARTY_ID 
LEFT OUTER JOIN HZ_CUST_SITE_USES_ALL        HCSUA_BILL         ON HCSUA_BILL.SITE_USE_ID = RCTA.BILL_TO_SITE_USE_ID 
LEFT OUTER JOIN HZ_CUST_ACCT_SITES_ALL       HCASA_BILL         ON HCASA_BILL.CUST_ACCT_SITE_ID = HCSUA_BILL.CUST_ACCT_SITE_ID 
LEFT OUTER JOIN HZ_PARTY_SITES               HPS_BILL           ON HPS_BILL.PARTY_SITE_ID = HCASA_BILL.PARTY_SITE_ID
LEFT OUTER JOIN HZ_LOCATIONS                 HL_BILL            ON HL_BILL.LOCATION_ID = HPS_BILL.LOCATION_ID 
LEFT OUTER JOIN HZ_CUST_ACCOUNT_ROLES        HCAR_BILL_C        ON HCAR_BILL_C.CUST_ACCOUNT_ROLE_ID = RCTA.BILL_TO_CONTACT_ID 
LEFT OUTER JOIN HZ_PARTIES                   HP_BILL_C          ON HP_BILL_C.PARTY_ID = HCAR_BILL_C.PARTY_ID  

WHERE 1=1
AND RCTA.INVOICE_CURRENCY_CODE      = 'USD'
AND RCTA.COMPLETE_FLAG              = 'Y'
AND TO_CHAR (RCTA.TRX_DATE, 'MM')  = NVL(:P_INVOICE_MONTH , TO_CHAR (RCTA.TRX_DATE, 'MM'))
AND TO_CHAR (RCTA.TRX_DATE, 'YYYY') = NVL(:P_INVOICE_YEAR , TO_CHAR (RCTA.TRX_DATE, 'YYYY'))
AND UPPER(RCTA.TRX_NUMBER)          = NVL(UPPER(:P_INVOICE_NUMBER), UPPER(RCTA.TRX_NUMBER))
AND HCA.ACCOUNT_NUMBER              = NVL(:P_CUSTOMER_NUMBER, HCA.ACCOUNT_NUMBER)
AND RCTA.ORG_ID                     = NVL(:P_ORGANIZATION_NUMBER,RCTA.ORG_ID)
